<?php

declare(strict_types=1);

namespace Waynestate\Squire\Facts;

use Waynestate\Squire\ToolError;

/**
 * The squire-facts markers, parsed and rendered as pure functions on a string plus an extension. No paths, no
 * I/O: the command hands a file's bytes in and gets the filled bytes back, unchanged outside the regions.
 */
final class Regions
{
    /** @var array<string, string> extension => marker style */
    private const STYLES = [
        'md' => 'html',
        'html' => 'html',
        'htm' => 'html',
        'js' => 'js',
        'mjs' => 'js',
        'cjs' => 'js',
        'css' => 'js',
        'yml' => 'yaml',
        'yaml' => 'yaml',
    ];

    /**
     * A marker is a whole line: optional leading whitespace, the marker, optional trailing whitespace. The start
     * marker may carry attributes after :start, kept as they are and ignored.
     *
     * @var array<string, string> style => regex, group 1 the indent, group 2 the key
     */
    private const START = [
        'html' => '/^(\s*)<!-- squire-facts:([a-z0-9][a-z0-9-]*):start( [^>]*)?-->\s*$/',
        'js' => '/^(\s*)\/\* squire-facts:([a-z0-9][a-z0-9-]*):start( [^*]*)?\*\/\s*$/',
        'yaml' => '/^(\s*)# squire-facts:([a-z0-9][a-z0-9-]*):start( .*)?$/',
    ];

    /** @var array<string, string> style => regex, group 1 the indent, group 2 the key */
    private const END = [
        'html' => '/^(\s*)<!-- squire-facts:([a-z0-9][a-z0-9-]*):end\s*-->\s*$/',
        'js' => '/^(\s*)\/\* squire-facts:([a-z0-9][a-z0-9-]*):end\s*\*\/\s*$/',
        'yaml' => '/^(\s*)# squire-facts:([a-z0-9][a-z0-9-]*):end\s*$/',
    ];

    /** @var array<string, string> style => the generated line that opens every filled region */
    private const GENERATED = [
        'html' => '<!-- generated by squire facts from .squire/facts.json; do not edit, run vendor/bin/squire facts -->',
        'js' => '/* generated by squire facts from .squire/facts.json; do not edit, run vendor/bin/squire facts */',
        'yaml' => '# generated by squire facts from .squire/facts.json; do not edit, run vendor/bin/squire facts',
    ];

    /**
     * Every well-formed region in the content, in start order. A malformed pairing (a start without an end, an
     * end without a start, a nested start, or a start and end with different keys) is a ToolError carrying
     * "<label>:<line>" so the command can point at the exact spot.
     *
     * @return list<array{key: string, line: int, indent: string, bodyStart: int, bodyEnd: int}>
     */
    public static function parse(string $content, string $extension, string $label = ''): array
    {
        $style = self::STYLES[strtolower($extension)] ?? null;
        if ($style === null) {
            return [];
        }

        $lines = self::splitLines($content);
        $regions = [];
        $open = null; // ?array{key: string, line: int, indent: string, bodyStart: int}
        foreach ($lines as $index => $line) {
            $number = $index + 1;
            $text = self::textOf($line);
            if (preg_match(self::START[$style], $text, $match) === 1) {
                if ($open !== null) {
                    throw new ToolError(self::at($label, $number, sprintf('squire-facts region "%s" starts inside region "%s".', $match[2], $open['key'])));
                }
                $open = ['key' => $match[2], 'line' => $number, 'indent' => $match[1], 'bodyStart' => $index + 1];
                continue;
            }
            if (preg_match(self::END[$style], $text, $match) === 1) {
                if ($open === null) {
                    throw new ToolError(self::at($label, $number, sprintf('squire-facts region "%s" ends without a start marker.', $match[2])));
                }
                if ($match[2] !== $open['key']) {
                    throw new ToolError(self::at($label, $number, sprintf('squire-facts region ends with key "%s" but was started with "%s".', $match[2], $open['key'])));
                }
                $regions[] = [
                    'key' => $open['key'],
                    'line' => $open['line'],
                    'indent' => $open['indent'],
                    'bodyStart' => $open['bodyStart'],
                    'bodyEnd' => $index,
                ];
                $open = null;
            }
        }
        if ($open !== null) {
            throw new ToolError(self::at($label, $open['line'], sprintf('squire-facts region "%s" starts here but never ends.', $open['key'])));
        }

        return $regions;
    }

    /**
     * Fills every region from the snapshot text: the generated line, then each line of the region text, every line
     * prefixed with the start marker's leading whitespace (an empty text line gets none). The file's own line
     * ending is used, bytes outside the regions never change, and a second run changes nothing.
     *
     * @param array<string, string> $values region key => exact body text; every parsed key must be present
     *
     * @return array{content: string, changed: list<array{key: string, line: int}>} the new content and the regions that drifted
     */
    public static function fill(string $content, string $extension, array $values): array
    {
        $style = self::STYLES[strtolower($extension)] ?? null;
        if ($style === null) {
            return ['content' => $content, 'changed' => []];
        }

        $lines = self::splitLines($content);
        $eol = self::eolOf($lines);
        $out = $lines;
        $changed = [];
        // Backwards, so filling one region never shifts the line numbers of the next.
        foreach (array_reverse(self::parse($content, $extension)) as $region) {
            $text = $values[$region['key']];
            $body = [self::GENERATED[$style]];
            if ($text !== '') {
                $body = array_merge($body, explode("\n", $text));
            }
            // Every line, generated line included, takes the start marker's leading whitespace; an empty line gets none.
            $rendered = [];
            foreach ($body as $line) {
                $rendered[] = ($line === '' ? '' : $region['indent'] . $line) . $eol;
            }
            $length = $region['bodyEnd'] - $region['bodyStart'];
            if (array_slice($lines, $region['bodyStart'], $length) !== $rendered) {
                array_splice($out, $region['bodyStart'], $length, $rendered);
                $changed[] = ['key' => $region['key'], 'line' => $region['line']];
            }
        }

        return ['content' => implode('', $out), 'changed' => array_reverse($changed)];
    }

    /** "<label>:<line>: " for error messages, or just "<line>: " when no label was given. */
    private static function at(string $label, int $line, string $message): string
    {
        return ($label === '' ? '' : $label . ':') . $line . ': ' . $message;
    }

    /** @return list<string> the lines, each keeping its "\n" terminator (and "\r" when the file is CRLF) */
    private static function splitLines(string $content): array
    {
        if ($content === '') {
            return [];
        }
        $parts = preg_split('/(?<=\n)/', $content);

        return is_array($parts) ? $parts : [];
    }

    /** The line without its terminator, so the marker regex sees one line of text. */
    private static function textOf(string $line): string
    {
        if (str_ends_with($line, "\n")) {
            $line = substr($line, 0, -1);
        }
        if (str_ends_with($line, "\r")) {
            $line = substr($line, 0, -1);
        }

        return $line;
    }

    /**
     * The file's own line ending: CRLF when its first line ends in CRLF, else LF.
     *
     * @param list<string> $lines
     */
    private static function eolOf(array $lines): string
    {
        return str_ends_with($lines[0] ?? '', "\r\n") ? "\r\n" : "\n";
    }
}
