<?php

declare(strict_types=1);

namespace Waynestate\Squire\Tests;

/**
 * `squire facts` (D-109, slice S1): the region filler and its drift check. The snapshot is read only here;
 * slice S2 writes it from CREED and ADVISOR data.
 */
final class FactsTest extends SquireTestCase
{
    private const GENERATED_MD = '<!-- generated by squire facts from .squire/facts.json; do not edit, run vendor/bin/squire facts -->';

    private const GENERATED_JS = '/* generated by squire facts from .squire/facts.json; do not edit, run vendor/bin/squire facts */';

    private const GENERATED_YAML = '# generated by squire facts from .squire/facts.json; do not edit, run vendor/bin/squire facts';

    /** A valid snapshot with the two regions every fixture below wants. */
    private const SNAPSHOT = '{"schema_version":1,"generated_on":"2026-11-11","generator":"squire facts 0.10.x","regions":{"preflight-pin":"0.8.0","cast-md":"- WayneUI\n- CREED","pins":"- preflight 0.8.0\n- helmet 0.9.0","cast-js":"\'WayneUI\',\n\'CREED\'"}}' . "\n";

    /** A temp dir holding the given snapshot (or none) plus the extra files. */
    private function factsApp(array $extra, ?string $snapshot = self::SNAPSHOT): string
    {
        $dir = $this->tempDir();
        if ($snapshot !== null) {
            $this->put($dir, '.squire/facts.json', $snapshot);
        }
        foreach ($extra as $path => $content) {
            $this->put($dir, $path, $content);
        }

        return $dir;
    }

    public function testAMarkdownRegionIsFilled(): void
    {
        $stale = "# App\n\nThe cast:\n<!-- squire-facts:cast-md:start -->\n- Stale entry\n<!-- squire-facts:cast-md:end -->\n\nFooter.\n";
        $dir = $this->factsApp(['README.md' => $stale]);

        $result = $this->runSquire(['facts', '--path=' . $dir]);

        self::assertSame(0, $result['exit'], $result['stderr']);
        self::assertStringContainsString('squire facts: filled 1 region(s) in 1 file(s)', $result['stdout']);
        $filled = (string) file_get_contents($dir . '/README.md');
        self::assertSame(
            "# App\n\nThe cast:\n<!-- squire-facts:cast-md:start -->\n" . self::GENERATED_MD . "\n- WayneUI\n- CREED\n<!-- squire-facts:cast-md:end -->\n\nFooter.\n",
            $filled,
            'the bytes outside the region stay exactly as they were',
        );

        // Idempotence: a second run changes nothing at all.
        $again = $this->runSquire(['facts', '--path=' . $dir]);
        self::assertSame(0, $again['exit'], $again['stderr']);
        self::assertStringContainsString('squire facts: filled 0 region(s) in 0 file(s)', $again['stdout']);
        self::assertSame($filled, (string) file_get_contents($dir . '/README.md'));
    }

    public function testCheckExitsOneOnDrift(): void
    {
        $stale = "# App\n\nThe cast:\n<!-- squire-facts:cast-md:start -->\n- Stale entry\n<!-- squire-facts:cast-md:end -->\n\nFooter.\n";
        $dir = $this->factsApp(['README.md' => $stale]);

        $result = $this->runSquire(['facts', '--check', '--path=' . $dir]);

        self::assertSame(1, $result['exit'], $result['stdout']);
        self::assertStringContainsString('README.md:4: cast-md is out of date (run vendor/bin/squire facts)', $result['stdout']);
        self::assertSame($stale, (string) file_get_contents($dir . '/README.md'), '--check writes nothing');
    }

    public function testCheckExitsZeroWhenInStep(): void
    {
        $dir = $this->factsApp(['README.md' => "# App\n\n<!-- squire-facts:cast-md:start -->\n- Stale entry\n<!-- squire-facts:cast-md:end -->\n"]);
        $this->runSquire(['facts', '--path=' . $dir]);

        $result = $this->runSquire(['facts', '--check', '--path=' . $dir]);

        self::assertSame(0, $result['exit'], $result['stdout']);
        self::assertStringContainsString('squire facts: 1 region(s) in step', $result['stdout']);
    }

    public function testYamlRegionKeepsIndentation(): void
    {
        $stale = "deploy:\n  includes:\n    # squire-facts:pins:start\n    - stale\n    # squire-facts:pins:end\n";
        $dir = $this->factsApp(['docker-compose.squire.yml' => $stale]);

        $result = $this->runSquire(['facts', '--path=' . $dir]);

        self::assertSame(0, $result['exit'], $result['stderr']);
        self::assertSame(
            "deploy:\n  includes:\n    # squire-facts:pins:start\n    " . self::GENERATED_YAML . "\n    - preflight 0.8.0\n    - helmet 0.9.0\n    # squire-facts:pins:end\n",
            (string) file_get_contents($dir . '/docker-compose.squire.yml'),
            'every body line, generated line included, takes the start marker\'s indent',
        );
    }

    public function testCrlfFileStaysCrlf(): void
    {
        $lf = "# App\r\n\r\n<!-- squire-facts:cast-md:start -->\r\n- Stale entry\r\n<!-- squire-facts:cast-md:end -->\r\n\r\nFooter.\r\n";
        $dir = $this->factsApp(['README.md' => $lf]);

        $result = $this->runSquire(['facts', '--path=' . $dir]);

        self::assertSame(0, $result['exit'], $result['stderr']);
        $expectedLf = "# App\n\n<!-- squire-facts:cast-md:start -->\n" . self::GENERATED_MD . "\n- WayneUI\n- CREED\n<!-- squire-facts:cast-md:end -->\n\nFooter.\n";
        self::assertSame(str_replace("\n", "\r\n", $expectedLf), (string) file_get_contents($dir . '/README.md'));
    }

    public function testJsRegion(): void
    {
        $stale = "export const CAST = [\n  /* squire-facts:cast-js:start */\n  'stale',\n  /* squire-facts:cast-js:end */\n];\n";
        $dir = $this->factsApp(['public/cast.js' => $stale]);

        $result = $this->runSquire(['facts', '--path=' . $dir]);

        self::assertSame(0, $result['exit'], $result['stderr']);
        self::assertSame(
            "export const CAST = [\n  /* squire-facts:cast-js:start */\n  " . self::GENERATED_JS . "\n  'WayneUI',\n  'CREED'\n  /* squire-facts:cast-js:end */\n];\n",
            (string) file_get_contents($dir . '/public/cast.js'),
        );
    }

    public function testStartAttributesAreKept(): void
    {
        $stale = "<!-- squire-facts:cast-md:start date=\"2026-11-09\" -->\n- Stale entry\n<!-- squire-facts:cast-md:end -->\n";
        $dir = $this->factsApp(['README.md' => $stale]);

        $result = $this->runSquire(['facts', '--path=' . $dir]);

        self::assertSame(0, $result['exit'], $result['stderr']);
        $filled = (string) file_get_contents($dir . '/README.md');
        self::assertStringStartsWith('<!-- squire-facts:cast-md:start date="2026-11-09" -->' . "\n", $filled, 'attributes are kept as they are');
        self::assertStringContainsString(self::GENERATED_MD . "\n- WayneUI\n- CREED\n", $filled);
    }

    public function testUnclosedRegionIsAToolError(): void
    {
        $dir = $this->factsApp(['README.md' => "# App\n\n<!-- squire-facts:cast-md:start -->\n- Stale entry\n\nNo end marker anywhere.\n"]);

        $result = $this->runSquire(['facts', '--path=' . $dir]);

        self::assertSame(2, $result['exit']);
        self::assertStringContainsString('README.md:3', $result['stderr'], 'the error names the file and the line');
        self::assertStringContainsString('cast-md', $result['stderr']);
    }

    public function testUnknownKeyIsAToolError(): void
    {
        $dir = $this->factsApp(['README.md' => "<!-- squire-facts:not-in-the-snapshot:start -->\nx\n<!-- squire-facts:not-in-the-snapshot:end -->\n"]);

        $result = $this->runSquire(['facts', '--path=' . $dir]);

        self::assertSame(2, $result['exit']);
        self::assertStringContainsString('not-in-the-snapshot', $result['stderr']);
    }

    public function testBadSchemaVersionIsAToolError(): void
    {
        $dir = $this->factsApp(
            ['README.md' => "<!-- squire-facts:cast-md:start -->\nx\n<!-- squire-facts:cast-md:end -->\n"],
            str_replace('"schema_version":1', '"schema_version":2', self::SNAPSHOT),
        );

        $result = $this->runSquire(['facts', '--path=' . $dir]);

        self::assertSame(2, $result['exit']);
        self::assertStringContainsString('schema_version', $result['stderr']);
    }

    public function testVendorIsSkipped(): void
    {
        $stale = "# App\n\n<!-- squire-facts:cast-md:start -->\n- Stale entry\n<!-- squire-facts:cast-md:end -->\n";
        $vendorStale = "<!-- squire-facts:cast-md:start -->\n- Even staler\n<!-- squire-facts:cast-md:end -->\n";
        $dir = $this->factsApp([
            'README.md' => $stale,
            'vendor/wayneui/cast.md' => $vendorStale,
        ]);

        $result = $this->runSquire(['facts', '--path=' . $dir]);

        self::assertSame(0, $result['exit'], $result['stderr']);
        self::assertStringContainsString('squire facts: filled 1 region(s) in 1 file(s)', $result['stdout']);
        self::assertStringNotContainsString('vendor', $result['stdout']);
        self::assertSame($vendorStale, (string) file_get_contents($dir . '/vendor/wayneui/cast.md'), 'vendor/ is left alone');

        $check = $this->runSquire(['facts', '--check', '--path=' . $dir]);
        self::assertSame(0, $check['exit'], $check['stdout']);
        self::assertStringContainsString('squire facts: 1 region(s) in step', $check['stdout']);
        self::assertStringNotContainsString('vendor', $check['stdout']);
    }
}
